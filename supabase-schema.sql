create table if not exists public.beds (
  code text not null,
  department text not null,
  room text not null default '',
  bed_type text not null check (bed_type in ('single', 'double')),
  status text not null check (status in ('available', 'occupied', 'cleaning')),
  patients text[] not null default '{}',
  since text not null default '',
  admitted_at text not null default '',
  discharged_at text not null default '',
  constraint beds_pkey primary key (code, room),
  constraint beds_patient_capacity check (
    cardinality(patients) <= case when bed_type = 'double' then 2 else 1 end
  ),
  constraint beds_occupancy_matches_patients check (
    (status = 'occupied' and cardinality(patients) > 0)
    or (status <> 'occupied' and cardinality(patients) = 0)
  )
);

alter table public.beds
  add column if not exists room text not null default '';

do $$
declare
  primary_key_name text;
begin
  select c.conname into primary_key_name
  from pg_constraint c
  where c.conrelid = 'public.beds'::regclass
    and c.contype = 'p';

  if primary_key_name is not null and not exists (
    select 1
    from pg_constraint c
    join pg_attribute a1
      on a1.attrelid = c.conrelid and a1.attnum = c.conkey[1]
    join pg_attribute a2
      on a2.attrelid = c.conrelid and a2.attnum = c.conkey[2]
    where c.conrelid = 'public.beds'::regclass
      and c.contype = 'p'
      and cardinality(c.conkey) = 2
      and a1.attname = 'code'
      and a2.attname = 'room'
  ) then
    execute format('alter table public.beds drop constraint %I', primary_key_name);
    alter table public.beds add constraint beds_pkey primary key (code, room);
  elsif primary_key_name is null then
    alter table public.beds add constraint beds_pkey primary key (code, room);
  end if;
end
$$;

create table if not exists public.patient_admissions (
  id bigint generated by default as identity primary key,
  bed_code text not null,
  department text not null,
  room text not null default '',
  patient_name text not null,
  admitted_at timestamptz not null default now(),
  discharged_at timestamptz,
  created_at timestamptz not null default now(),
  constraint patient_admissions_time_order check (
    discharged_at is null or discharged_at >= admitted_at
  )
);

