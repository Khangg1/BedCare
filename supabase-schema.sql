create or replace function public.bedcare_parse_local_timestamp(value text)
returns timestamptz
language plpgsql
immutable
set search_path = ''
as $$
begin
  if value is null or btrim(value) = '' then
    return null;
  end if;
  if value ~* '(Z|[+-][0-9]{2}(:?[0-9]{2})?)$' then
    return value::timestamptz;
  end if;
  if value ~ '^[0-9]{1,2}/[0-9]{1,2}/[0-9]{4}$' then
    return to_date(value, 'DD/MM/YYYY')::timestamp at time zone 'Asia/Ho_Chi_Minh';
  end if;
  return value::timestamp at time zone 'Asia/Ho_Chi_Minh';
end;
$$;
revoke all on function public.bedcare_parse_local_timestamp(text) from public;

create or replace function public.track_bed_patient_admissions()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  previous_patients text[] := '{}';
  current_patients text[] := '{}';
  v_patient_name text;
  discharge_time timestamptz;
  admission_time timestamptz;
  bed_identity_changed boolean := false;
begin
  if tg_op = 'UPDATE' and old.status = 'occupied' then
    previous_patients := coalesce(old.patients, '{}');
    bed_identity_changed := old.code <> new.code or old.room <> new.room;
  end if;

  if new.status = 'occupied' then
    current_patients := coalesce(new.patients, '{}');
  end if;

  discharge_time := coalesce(
    public.bedcare_parse_local_timestamp(new.discharged_at),
    now()
  );
  admission_time := coalesce(
    public.bedcare_parse_local_timestamp(new.admitted_at),
    public.bedcare_parse_local_timestamp(new.since),
    now()
  );

  foreach v_patient_name in array previous_patients loop
    if bed_identity_changed or not (v_patient_name = any(current_patients)) then
      update public.patient_admissions as pa
      set discharged_at = discharge_time
      where pa.bed_code = old.code
        and pa.room = old.room
        and pa.patient_name = v_patient_name
        and pa.discharged_at is null;
    end if;
  end loop;

  foreach v_patient_name in array current_patients loop
    if btrim(v_patient_name) <> '' and not exists (
      select 1
      from public.patient_admissions as pa
      where pa.bed_code = new.code
        and pa.room = new.room
        and pa.patient_name = btrim(v_patient_name)
        and pa.discharged_at is null
    ) then
      insert into public.patient_admissions (bed_code, department, room, patient_name, admitted_at)
      values (new.code, new.department, new.room, btrim(v_patient_name), admission_time);
    else
      update public.patient_admissions as pa
      set department = new.department,
          room = new.room
      where pa.bed_code = new.code
        and pa.room = new.room
        and pa.patient_name = btrim(v_patient_name)
        and pa.discharged_at is null
        and (pa.department <> new.department or pa.room <> new.room);
    end if;
  end loop;

  return new;
end;
$$;
revoke all on function public.track_bed_patient_admissions() from public;

drop trigger if exists beds_track_patient_admissions on public.beds;
create trigger beds_track_patient_admissions
  after insert or update of code, status, patients, department, room, admitted_at, discharged_at
  on public.beds
  for each row execute function public.track_bed_patient_admissions();

create or replace function public.close_deleted_bed_admissions()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.patient_admissions
  set discharged_at = greatest(now(), admitted_at)
  where bed_code = old.code
    and room = old.room
    and discharged_at is null;
  return old;
end;
$$;
revoke all on function public.close_deleted_bed_admissions() from public;

drop trigger if exists beds_close_patient_admissions on public.beds;
create trigger beds_close_patient_admissions
  after delete on public.beds
  for each row execute function public.close_deleted_bed_admissions();

insert into public.patient_admissions (bed_code, department, room, patient_name, admitted_at)
select distinct
       b.code,
       b.department,
       b.room,
       btrim(patients.patient_name),
       coalesce(
         public.bedcare_parse_local_timestamp(b.admitted_at),
         public.bedcare_parse_local_timestamp(b.since),
         now()
       )
from public.beds b
cross join lateral unnest(b.patients) as patients(patient_name)
where b.status = 'occupied'
  and btrim(patients.patient_name) <> ''
  and not exists (
    select 1
    from public.patient_admissions a
    where a.bed_code = b.code
      and a.room = b.room
      and a.patient_name = btrim(patients.patient_name)
      and a.discharged_at is null
  );

