create or replace function public.is_hospital_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.hospital_members
    where user_id = (select auth.uid())
      and role = 'admin'
  );
$$;

revoke all on function public.is_hospital_admin() from public;
grant execute on function public.is_hospital_admin() to authenticated;

create or replace function public.can_access_department(department_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_hospital_admin() or exists (
    select 1 from public.hospital_members
    where user_id = (select auth.uid())
      and role = 'member'
      and department = department_name
  );
$$;

revoke all on function public.can_access_department(text) from public;
grant execute on function public.can_access_department(text) to authenticated;

